// Base path for sign images (adjust based on where you place images)
export const SIGN_IMAGE_BASE_PATH = "/signs/";

// Function to get sign image path for a word
export function getSignImagePath(word) {
  const normalizedWord = word.toLowerCase().trim();
  const imageName = signMapping[normalizedWord];
  
  if (imageName) {
    return `${SIGN_IMAGE_BASE_PATH}${imageName}`;
  }
  
  return null; // Word not in mapping
}

// Function to convert text to array of sign image paths
export function textToSignImages(text) {
  // Remove punctuation and split into words
  const words = text
    .toLowerCase()
    .replace(/[.,!?;:]/g, '')
    .split(/\s+/)
    .filter(word => word.length > 0);
  
  return words.map(word => ({
    word: word,
    imagePath: getSignImagePath(word)
  }));
}
